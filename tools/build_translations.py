def write_po(language, messages):
    target = BASE_DIR / "locale" / language / "LC_MESSAGES"
    target.mkdir(parents=True, exist_ok=True)
    header = (
        "Project-Id-Version: MMS 1.0\n"
        f"Language: {language}\n"
        "Content-Type: text/plain; charset=UTF-8\n"
        "Content-Transfer-Encoding: 8bit\n"
        "Plural-Forms: nplurals=2; plural=(n != 1);\n"
    )
    catalog = {"": header, **messages}
    lines = []
    for source, translated in catalog.items():
        lines.extend([f"msgid {json.dumps(source, ensure_ascii=False)}", f"msgstr {json.dumps(translated, ensure_ascii=False)}", ""])
    (target / "django.po").write_text("\n".join(lines), encoding="utf-8")
    write_mo(catalog, target / "django.mo")


def write_mo(messages, path):
    keys = sorted(messages)
    originals = [key.encode("utf-8") for key in keys]
    translations = [messages[key].encode("utf-8") for key in keys]
    count = len(keys)
    original_table = 28
    translation_table = original_table + count * 8
    original_data = translation_table + count * 8
    original_blob = b"".join(value + b"\0" for value in originals)
    translation_data = original_data + len(original_blob)
    output = [struct.pack("<7I", 0x950412DE, 0, count, original_table, translation_table, 0, 0)]
    offset = original_data
    for value in originals:
        output.append(struct.pack("<2I", len(value), offset))
        offset += len(value) + 1
    offset = translation_data
    for value in translations:
        output.append(struct.pack("<2I", len(value), offset))
        offset += len(value) + 1
    output.extend([original_blob, b"".join(value + b"\0" for value in translations)])
    path.write_bytes(b"".join(output))


